const { launch, BROWSER } = require('./lib');
const fs = require('fs');
(async () => {
  const b = await launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
  const p = await ctx.newPage(); const errs = [];
  p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
  await p.goto('http://localhost:8080/', { waitUntil: 'load' }); await p.waitForTimeout(800);
  const r = {};
  await p.keyboard.press('Tab'); r.firstTab = await p.evaluate(() => document.activeElement.textContent.trim());
  await p.keyboard.press('Control+k'); await p.waitForTimeout(400);
  r.cmdkOpen = await p.evaluate(() => !document.querySelector('[data-cmdk]').hidden && document.activeElement.matches('[data-cmdk-input]'));
  await p.keyboard.type('tarif'); r.cmdkResults = await p.$$eval('#cmdk-list li', l => l.map(x => x.textContent));
  await p.keyboard.press('Enter'); await p.waitForTimeout(1500);
  r.afterCmd = await p.evaluate(() => ({ hidden: document.querySelector('[data-cmdk]').hidden, tarifTop: Math.round(document.getElementById('tarifs').getBoundingClientRect().top) }));
  await p.keyboard.press('Control+k'); await p.waitForTimeout(300); await p.keyboard.press('Escape'); await p.waitForTimeout(600);
  r.escClosed = await p.evaluate(() => document.querySelector('[data-cmdk]').hidden);
  await p.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; document.getElementById('actions').scrollIntoView(); }); await p.waitForTimeout(800);
  const rows = await p.$$('.act-row .act-front .who');
  await rows[0].click(); await rows[1].click(); await p.waitForTimeout(500);
  r.bar = await p.evaluate(() => ({ hidden: document.querySelector('[data-act-bar]').hidden, txt: document.querySelector('[data-act-count]').textContent }));
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('[data-act="csv"]')]);
  const csv = fs.readFileSync(await dl.path(), 'utf8'); r.csv = JSON.stringify(csv.slice(0, 80));
  await p.click('[data-act="archive"]'); await p.waitForTimeout(900);
  r.afterArchive = await p.$$eval('.act-row', l => l.length);
  await p.locator('.toast .t-undo').last().click(); await p.waitForTimeout(900);
  r.afterUndo = await p.$$eval('.act-row', l => l.map(x => x.style.opacity + '|' + x.querySelector('.who b').textContent));
  const box = await (await p.$('.act-row:nth-child(3) .act-front')).boundingBox();
  await p.mouse.move(box.x + box.width - 40, box.y + 20); await p.mouse.down();
  for (let i = 1; i <= 6; i++) { await p.mouse.move(box.x + box.width - 40 - i * 25, box.y + 20); await p.waitForTimeout(16); }
  await p.mouse.up(); await p.waitForTimeout(900);
  r.swipe = await p.$eval('.act-row:nth-child(3) .act-front', e => e.style.transform);
  await p.click('#tab-cand'); await p.waitForTimeout(900);
  r.views = await p.evaluate(() => ({ cand: !document.querySelector('[data-pane="candidat"]').hidden, agent: document.querySelector('[data-pane="agent"]').hidden, sel: document.getElementById('tab-cand').getAttribute('aria-selected') }));
  await p.click('[data-car-next]'); await p.waitForTimeout(900);
  r.car = await p.$eval('[data-car-track]', e => e.style.transform);
  await p.locator('#faq summary').first().click(); await p.waitForTimeout(500);
  r.faq = await p.$eval('#faq details', d => d.open);
  await p.click('[data-billing="year"]'); await p.waitForTimeout(700);
  r.price = await p.$eval('[data-price-unit]', e => e.textContent);
  await p.click('[data-demo-form] button[type=submit]'); await p.waitForTimeout(300);
  r.formErrs = await p.$$eval('.err', l => l.map(e => e.textContent).filter(Boolean).length);
  r.focusAfterSubmit = await p.evaluate(() => document.activeElement.id);
  await p.focus('[data-theme-toggle]'); await p.waitForTimeout(500); await p.keyboard.press('Enter'); await p.waitForTimeout(700);
  r.theme = await p.evaluate(() => document.documentElement.dataset.theme);
  console.log(BROWSER, JSON.stringify(r, null, 1)); console.log('errors', errs);
  await b.close();
})();
